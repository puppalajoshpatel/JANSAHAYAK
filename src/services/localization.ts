export function getLocalizedCategory(category: GrievanceCategory, langCode: string = 'en'): CategoryTranslation {
  const code = (langCode || 'en').split('-')[0].toLowerCase();
  const englishTitle = CATEGORY_LOCALIZED[category]?.en || category;
  const regionalTitle = CATEGORY_LOCALIZED[category]?.[code] || CATEGORY_LOCALIZED[category]?.hi || englishTitle;
  
  return {
    label: englishTitle,
    regional: regionalTitle
  };
}

